ORIGINAL = Catalog(
    col_type="integer",
    col_identity="",
    sequence="public.t_id_seq",
    sequence_type="integer",
    pk_constraint="t_pkey",
    pk_columns=("id",),
    inbound_fks=(),
    other_indexes_on_col=(),
    has_shadow_col=False,
    has_trigger=False,
    check_validated=None,
    shadow_index_valid=None,
)
SHADOW = {"has_shadow_col": True, "has_trigger": True}


@pytest.mark.parametrize(
    "facts, expected",
    [
        ({}, Phase.ORIGINAL),
        ({**SHADOW, "check_validated": False}, Phase.SHADOW_INSTALLED),
        ({**SHADOW, "check_validated": True}, Phase.SHADOW_FILLED),
        (
            {**SHADOW, "check_validated": True, "shadow_index_valid": False},
            Phase.SHADOW_FILLED,
        ),
        (
            {**SHADOW, "check_validated": True, "shadow_index_valid": True},
            Phase.SHADOW_INDEXED,
        ),
        ({"col_type": "bigint", "sequence_type": "bigint"}, Phase.CONVERTED),
    ],
)
def test_phase_is_derived_from_catalog_facts(facts, expected):
    assert replace(ORIGINAL, **facts).phase() == expected


@pytest.mark.parametrize(
    "facts",
    [
        {"has_shadow_col": True},
        {"has_trigger": True, "check_validated": False},
        {**SHADOW},
        {**SHADOW, "check_validated": False, "shadow_index_valid": True},
        {"shadow_index_valid": True},
        {"col_type": "bigint", **SHADOW, "check_validated": True},
    ],
)
def test_contradictory_catalog_facts_raise(facts):
    with pytest.raises(InconsistentState):
        replace(ORIGINAL, **facts).phase()


def test_non_integer_column_is_unsupported():
    with pytest.raises(Unsupported):
        replace(ORIGINAL, col_type="smallint").phase()


def test_tuning_from_env_rejects_non_positive_batch():
    assert Tuning.from_env({}) == Tuning()
    assert Tuning.from_env(
        {"BIGINT_BACKFILL_BATCH_SIZE": "10", "BIGINT_BACKFILL_PAUSE_MS": "250"}
    ) == Tuning(batch_size=10, pause_s=0.25)
    with pytest.raises(ValueError):
        Tuning.from_env({"BIGINT_BACKFILL_BATCH_SIZE": "0"})
